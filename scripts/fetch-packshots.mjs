// Builds src/data/packshots.js — extra photo angles for the Open Food Facts
// products in the catalog, so those cards can show a real multi-angle carousel
// instead of one static front-of-pack shot.
//
// Why OFF and not stock video: product video is not sourceable (a Commons search
// for rotating sneakers or watches returns nothing, and the few real product
// clips run 22MB-800MB against a 7.6MB site). OFF, however, already holds
// front / ingredients / nutrition / packaging shots per barcode — genuinely the
// same product from several sides, free, and hotlinkable like the fronts already
// are. For a site whose whole point is what sits inside a price, the ingredients
// and nutrition panels are the most on-theme second image available.
//
// The variant revision numbers differ per image, so they cannot be guessed by
// string-swapping front_en -> back_en; each has to come from the API.
import fs from 'node:fs'
import { TEMPLATE_HEROES } from '../src/data/products.js'

// `packaging` is excluded deliberately: on Indian packs it is almost always the
// recycling symbol or a barcode, which tells a shopper nothing.
const ORDER = ['front', 'ingredients', 'nutrition']
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

// /images/products/890/171/913/4845/front_en.11.full.jpg -> 8901719134845
const barcodeOf = (url) => {
  const m = url.match(/\/products\/((?:\d+\/)+)/)
  return m ? m[1].replace(/\//g, '') : null
}

const codes = new Map()
for (const p of TEMPLATE_HEROES) {
  if (!/images\.openfoodfacts\.org/.test(p.img)) continue
  const c = barcodeOf(p.img)
  if (c && !codes.has(c)) codes.set(c, p.baseName)
}
console.log(`OFF products in catalog: ${codes.size}`)

const out = {}
let i = 0, withExtra = 0, failed = 0, dropped = 0
for (const [code, name] of codes) {
  i++
  let si = null, sizes = {}
  for (let attempt = 0; attempt < 4 && si === null; attempt++) {
    try {
      const r = await fetch(`https://world.openfoodfacts.org/api/v2/product/${code}.json?fields=selected_images,images`, {
        headers: { 'User-Agent': 'thodasa-packshots/1.0 (bhaumik.tandan@enablix.com)' },
      })
      if (r.status === 429 || r.status >= 500) { await sleep(2000 * (attempt + 1)); continue }
      if (!r.ok) break
      const body = (await r.json()).product ?? {}
      si = body.selected_images ?? {}
      sizes = body.images ?? {}
    } catch { await sleep(1500) }
  }
  if (si === null) { failed++; await sleep(800); continue }
  try {
    const urls = []
    for (const kind of ORDER) {
      const disp = si[kind]?.display
      if (!disp) continue
      const u = disp.en
      if (!u) continue // English only: OFF is global and a German ingredients
                       // panel on an Indian pack is just noise here
      const full = u.replace(/\.400\.jpg$/, '.full.jpg')
      const rev = full.match(/\.(\d+)\.full\.jpg$/)?.[1]
      const dim = rev && sizes[rev]?.sizes?.full
      if (dim?.w && dim?.h) {
        const ratio = dim.w / dim.h
        if (ratio < 0.5 || ratio > 1.5) { dropped++; continue }
      }
      if (!urls.includes(full)) urls.push(full)
    }
    if (urls.length > 1) { out[code] = urls; withExtra++ }
    if (i % 25 === 0) console.log(`  ${i}/${codes.size} … ${withExtra} with extra angles`)
  } catch { /* skip */ }
  await sleep(900) // be polite to a free community API
}

fs.writeFileSync(
  'src/data/packshots.js',
  '// GENERATED by scripts/fetch-packshots.mjs — do not edit by hand.\n' +
  '// barcode -> [front, packaging, ingredients, nutrition] photo URLs.\n' +
  'export default ' + JSON.stringify(out, null, 1) + '\n',
)
const angles = Object.values(out).reduce((s, a) => s + a.length, 0)
console.log(`wrote ${withExtra} products, ${angles} photos (avg ${(angles / (withExtra || 1)).toFixed(1)} each)`)
console.log(`dropped ${dropped} angles for unreadable aspect ratio`)
if (failed) console.log(`FAILED after retries: ${failed} — rerun to pick these up`)
